"""Cut a source release of IMRI.

The only supported way to produce something you can hand to someone else, or
come back to in six months when you want to start version two. It exists
because "zip the folder" ships the wrong things: a build directory, a test
database, an activated licence file, and no way to tell whether the copy you
sent is the copy that passed the tests.

What it does, in order:

1. Reads the version from ``imri/config.py:APP_VERSION``. There is no second
   copy of the version number, so there is nothing to fall out of step.
2. Stages a clean tree into ``release/IMRI-<version>/``. Build junk, caches,
   ``build/``, ``dist/``, ``data/``, ``.tmpdata/``, ``reference/`` and
   ``.workbuddy-ai/`` are excluded **by rule** — so the next release cannot
   accidentally ship somebody's test database.

   Re-running it over an existing folder does not delete the folder. It
   overwrites in place and removes only files that are no longer part of the
   release, so a re-release cannot destroy anything it did not write. Pass
   ``--clean`` if you really do want the folder wiped first.
3. Copies ``dist/IMRI.exe`` in as ``IMRI.exe`` unless ``--no-exe``.
4. Writes ``MANIFEST.txt``: every file with its size and SHA-256.
5. Verifies **the staged copy, not the working tree**: runs the full test suite
   from inside the staged folder, and runs the bundled exe's ``--check``. A
   release that cannot pass its own tests is not produced.
6. Zips to ``release/IMRI-<version>.zip``.

Usage::

    python release.py                  # stage, zip, verify
    python release.py --no-verify      # stage and zip only
    python release.py --no-exe         # source only
    python release.py --out D:\\builds  # somewhere else

Exit codes: 0 released and verified, 1 verification failed, 2 preflight failed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
APP_NAME = "IMRI"


def _version() -> str:
    """Return ``config.APP_VERSION`` from the tree being released."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    try:
        from imri import config  # noqa: PLC0415 - deliberately late

        return str(config.APP_VERSION)
    except Exception as exc:  # pragma: no cover - defensive
        raise SystemExit(f"could not read APP_VERSION from imri/config.py: {exc}")


def _schema() -> int:
    """Return ``config.SCHEMA_VERSION`` — what the bundled exe must report."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    try:
        from imri import config  # noqa: PLC0415 - deliberately late

        return int(config.SCHEMA_VERSION)
    except Exception as exc:  # pragma: no cover - defensive
        raise SystemExit(f"could not read SCHEMA_VERSION from imri/config.py: {exc}")


#: Top-level entries that ship. Anything not listed is not released, which is
#: the safer default: a new scratch folder is invisible until someone adds it
#: here on purpose.
SHIP = (
    "main.py",
    "build_exe.py",
    "release.py",
    "build.bat",
    "run.bat",
    "README.md",
    "CHANGELOG.md",
    "DEVELOPING.md",
    ".gitignore",
    ".gitattributes",
    "imri",
    "web",
    "tests",
    "tools",
    "docs",
    "imri-docs",
)

#: Directories skipped at any depth, wherever they appear.
JUNK_DIRS = frozenset(
    {
        "__pycache__",
        ".git",
        ".workbuddy-ai",
        ".venv",
        "venv",
        ".idea",
        ".vscode",
        "node_modules",
    }
)

#: Files skipped at any depth. ``*.spec`` is regenerated by build_exe.py.
JUNK_FILES = frozenset({".DS_Store", "Thumbs.db", "desktop.ini"})
JUNK_SUFFIXES = frozenset({".pyc", ".pyo", ".log", ".tmp", ".spec"})


# --------------------------------------------------------------------------- #
# Output helpers
# --------------------------------------------------------------------------- #

def step(text: str) -> None:
    print(f"\n== {text}")


def info(text: str) -> None:
    print(f"   {text}")


def warn(text: str) -> None:
    print(f"   !  {text}")


def fail(text: str) -> None:
    print(f"   FAIL  {text}")


# --------------------------------------------------------------------------- #
# Staging
# --------------------------------------------------------------------------- #

def _skip(path: Path) -> bool:
    """Return True when ``path`` must not be copied into the release."""
    if path.is_dir():
        return path.name in JUNK_DIRS
    if path.name in JUNK_FILES:
        return True
    return path.suffix.lower() in JUNK_SUFFIXES


def _copy_tree(source: Path, target: Path, root: Path, collected: set[str]) -> tuple[int, int]:
    """Copy ``source`` to ``target``, skipping junk. Return (files, bytes).

    Every path written is recorded in ``collected`` **relative to ``root``**
    (the release root), which is the same form ``_remove_strays`` compares
    against. Mixing the two forms would delete the whole tree, so this is the
    one invariant in the file that must not drift.
    """
    files = 0
    total = 0
    if source.is_file():
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        collected.add(target.relative_to(root).as_posix())
        return 1, source.stat().st_size

    for current, dirnames, filenames in os.walk(source):
        here = Path(current)
        dirnames[:] = sorted(d for d in dirnames if not _skip(here / d))
        relative = here.relative_to(source)
        (target / relative).mkdir(parents=True, exist_ok=True)
        for filename in sorted(filenames):
            candidate = here / filename
            if _skip(candidate):
                continue
            written = target / relative / filename
            shutil.copy2(candidate, written)
            collected.add(written.relative_to(root).as_posix())
            files += 1
            total += candidate.stat().st_size
    return files, total


def _remove_strays(stage: Path, expected: set[str]) -> int:
    """Delete files in ``stage`` that are not part of this release.

    Only files this script would have written are ever considered, and only
    when they are genuinely absent from the release — normally the count is
    zero. That is deliberate: re-cutting a release must not be able to take
    anything with it that it did not put there.

    The floor below is not decoration. ``expected`` is built while copying, so
    a bug that leaves it empty would turn this function into "delete the
    release", and the caller would happily report success. A release is never
    smaller than a few dozen files, so refuse to act on an implausible set.
    """
    if len(expected) < 20:
        raise SystemExit(
            f"refusing to prune: only {len(expected)} expected files — the "
            "staging list is wrong, so pruning would delete the release"
        )

    removed = 0
    for current, dirnames, filenames in os.walk(stage, topdown=False):
        here = Path(current)
        for filename in filenames:
            path = here / filename
            if path.relative_to(stage).as_posix() not in expected:
                path.unlink()
                removed += 1
        # Prune directories that the release no longer contains.
        if here != stage:
            try:
                here.rmdir()
            except OSError:
                pass
    return removed


def _preflight(exe_required: bool) -> list[str]:
    """Return a list of problems that should stop the release."""
    problems: list[str] = []
    for entry in SHIP:
        if not (ROOT / entry).exists():
            problems.append(f"{entry} is missing")
    for doc in ("README.md", "CHANGELOG.md", "DEVELOPING.md"):
        if not (ROOT / doc).is_file():
            problems.append(f"{doc} is missing — the release is undocumented")
    if exe_required and not (ROOT / "dist" / f"{APP_NAME}.exe").is_file():
        problems.append(
            "dist/IMRI.exe is missing — run build_exe.py first, or pass --no-exe"
        )
    return problems


def _manifest(stage: Path, version: str) -> Path:
    """Write MANIFEST.txt listing every shipped file with its SHA-256."""
    rows: list[tuple[str, int, str]] = []
    for current, dirnames, filenames in os.walk(stage):
        dirnames.sort()
        for filename in sorted(filenames):
            path = Path(current) / filename
            relative = path.relative_to(stage).as_posix()
            if relative == "MANIFEST.txt":
                continue
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            rows.append((relative, path.stat().st_size, digest))

    lines = [
        f"{APP_NAME} {version}",
        "",
        f"{len(rows)} files",
        f"{sum(size for _, size, _ in rows):,} bytes",
        "",
        "SHA-256 of every file in this release, so two copies can be compared",
        "without trusting the archive they arrived in.",
        "",
        f"{'sha256':<64}  {'bytes':>10}  path",
        f"{'-' * 64}  {'-' * 10}  {'-' * 40}",
    ]
    for relative, size, digest in rows:
        lines.append(f"{digest}  {size:>10,}  {relative}")

    target = stage / "MANIFEST.txt"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


def _zip(stage: Path, archive: Path) -> int:
    """Zip ``stage`` so it extracts to a single top-level folder."""
    count = 0
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as bundle:
        for current, dirnames, filenames in os.walk(stage):
            dirnames.sort()
            for filename in sorted(filenames):
                path = Path(current) / filename
                bundle.write(path, path.relative_to(stage.parent).as_posix())
                count += 1
    return count


# --------------------------------------------------------------------------- #
# Verification — against the staged copy, never the working tree
# --------------------------------------------------------------------------- #

def _run(command: list[str], cwd: Path, timeout: float) -> tuple[int, str]:
    try:
        completed = subprocess.run(
            command,
            cwd=str(cwd),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=timeout,
        )
        return completed.returncode, completed.stdout or ""
    except subprocess.TimeoutExpired as exc:
        captured = exc.output or ""
        if isinstance(captured, bytes):
            captured = captured.decode(errors="replace")
        return 124, captured + "\n[timed out]"
    except OSError as exc:
        return 127, str(exc)


def _verify_tests(stage: Path) -> bool:
    """Run the full suite from inside the staged tree."""
    step("Verifying: test suite, from the staged copy")
    code, output = _run(
        [sys.executable, str(stage / "tests" / "run_all.py"), "--quiet"],
        cwd=stage,
        timeout=900,
    )
    tail = [line for line in output.strip().splitlines() if line.strip()][-6:]
    for line in tail:
        info(line)
    if code != 0:
        fail("the staged copy does not pass its own tests")
        return False
    return True


def _verify_exe(stage: Path, expected_schema: int) -> bool:
    """Run the bundled exe's self-check against a throwaway data directory.

    ``--check`` starts the real server on a free port, builds a fresh database,
    prints a JSON summary and exits. Parsing that summary is a stronger test
    than "the process started": it proves the frozen bundle can create the
    schema, seed the admin, and read its own settings — the things that break
    when a data file is left out of the bundle.

    Counts are asserted as *minimums*, not equalities, so adding an index in
    version two does not fail the release.
    """
    exe = stage / f"{APP_NAME}.exe"
    if not exe.is_file():
        info("no exe in this release — skipped")
        return True

    step("Verifying: bundled exe self-check")
    scratch = Path(tempfile.mkdtemp(prefix="imri-release-check-"))
    try:
        code, output = _run(
            [str(exe), "--check", "--data-dir", str(scratch)],
            cwd=stage,
            timeout=180,
        )
        if code != 0:
            for line in output.strip().splitlines()[-8:]:
                info(line)
            fail(f"the bundled exe exited {code}")
            return False

        # The summary is JSON. Anything before the first brace is progress
        # chatter, so start there rather than requiring a clean stream.
        start = output.find("{")
        try:
            payload = json.loads(output[start:]) if start >= 0 else {}
        except json.JSONDecodeError:
            payload = {}
        if not isinstance(payload, dict) or not payload:
            for line in output.strip().splitlines()[-8:]:
                info(line)
            fail("the exe did not print a JSON summary")
            return False

        objects = payload.get("objects") or {}
        rows = payload.get("row_counts") or {}
        checks = [
            ("schema version is %d" % expected_schema,
             payload.get("schema") == expected_schema, payload.get("schema")),
            ("at least 18 tables", int(objects.get("tables") or 0) >= 18, objects.get("tables")),
            ("at least 40 indexes", int(objects.get("indexes") or 0) >= 40, objects.get("indexes")),
            ("at least 2 triggers", int(objects.get("triggers") or 0) >= 2, objects.get("triggers")),
            ("settings seeded", int(payload.get("settings") or 0) >= 19, payload.get("settings")),
            ("admin user seeded", int(rows.get("users") or 0) == 1, rows.get("users")),
            ("starts unlicensed", payload.get("licensed") is False, payload.get("licensed")),
        ]
        ok = True
        for label, passed, actual in checks:
            info(f"{'ok  ' if passed else 'FAIL'}  {label} (got {actual!r})")
            ok = ok and passed
        return ok
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


def _verify_shape(stage: Path) -> bool:
    """Assert the staged tree contains nothing it should not."""
    step("Verifying: staged tree contains no junk")
    problems: list[str] = []
    for current, dirnames, filenames in os.walk(stage):
        for name in list(dirnames):
            if name in JUNK_DIRS:
                problems.append(f"junk directory: {(Path(current) / name).relative_to(stage)}")
        for filename in filenames:
            if filename.endswith((".pyc", ".pyo")):
                problems.append(f"bytecode: {(Path(current) / filename).relative_to(stage)}")

    for forbidden in ("data", ".tmpdata", "build", "dist", "reference"):
        if (stage / forbidden).exists():
            problems.append(f"{forbidden}/ should not be in a release")

    for required in (
        "main.py",
        "README.md",
        "CHANGELOG.md",
        "DEVELOPING.md",
        "MANIFEST.txt",
        "imri/config.py",
        "web/index.html",
        "web/js/brand.js",
        "tests/run_all.py",
    ):
        if not (stage / required).exists():
            problems.append(f"{required} is missing")

    for problem in problems:
        fail(problem)
    return not problems


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Cut a source release of IMRI.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--out", default=str(ROOT / "release"),
                        help="Where to write the release (default: ./release).")
    parser.add_argument("--no-exe", action="store_true",
                        help="Source only; do not require or copy dist/IMRI.exe.")
    parser.add_argument("--no-verify", action="store_true",
                        help="Stage and zip without running the tests.")
    parser.add_argument("--clean", action="store_true",
                        help="Wipe the release folder first instead of updating it in place.")
    args = parser.parse_args(argv)

    version = _version()
    schema = _schema()
    out_dir = Path(args.out).expanduser().resolve()
    stage = out_dir / f"{APP_NAME}-{version}"
    archive = out_dir / f"{APP_NAME}-{version}.zip"

    print(f"{APP_NAME} {version} — cutting a release")
    print(f"   source  {ROOT}")
    print(f"   output  {out_dir}")

    step("Preflight")
    problems = _preflight(exe_required=not args.no_exe)
    for problem in problems:
        fail(problem)
    if problems:
        return 2
    info("all expected inputs present")

    if stage.exists() and args.clean:
        info(f"wiping the previous {stage.name}/ (--clean)")
        shutil.rmtree(stage)
    stage.mkdir(parents=True, exist_ok=True)

    # -- stage ---------------------------------------------------------- #
    step("Staging")
    source_files = 0
    source_bytes = 0
    expected: set[str] = set()
    for entry in SHIP:
        copied, size = _copy_tree(ROOT / entry, stage / entry, stage, expected)
        source_files += copied
        source_bytes += size
        if copied:
            info(f"{entry:<14} {copied:>4} files")
        else:
            warn(f"{entry:<14} empty")

    (stage / "VERSION").write_text(version + "\n", encoding="utf-8")
    expected.add("VERSION")
    source_files += 1
    info(f"{'VERSION':<14}    1 file")

    exe_bytes = 0
    if not args.no_exe:
        shutil.copy2(ROOT / "dist" / f"{APP_NAME}.exe", stage / f"{APP_NAME}.exe")
        expected.add(f"{APP_NAME}.exe")
        exe_bytes = (stage / f"{APP_NAME}.exe").stat().st_size
        info(f"{'IMRI.exe':<14} {exe_bytes / 1_048_576:>7.1f} MB")

    manifest = _manifest(stage, version)
    expected.add("MANIFEST.txt")
    info(f"{'MANIFEST.txt':<14} {len(manifest.read_text(encoding='utf-8').splitlines()):>4} lines")

    removed = _remove_strays(stage, expected)
    if removed:
        info(f"removed {removed} file(s) left over from a previous release")

    info(f"{source_files} source files, {source_bytes / 1_048_576:.1f} MB"
         + (f", plus a {exe_bytes / 1_048_576:.1f} MB exe" if exe_bytes else ""))

    # -- verify --------------------------------------------------------- #
    ok = _verify_shape(stage)
    if ok and not args.no_verify:
        ok = _verify_tests(stage) and _verify_exe(stage, schema)
    elif not args.no_verify:
        fail("skipping the test run because the staged tree is wrong")
        ok = False

    if not ok:
        print(f"\n   Release NOT produced. The staged tree is left at:\n   {stage}")
        return 1

    # -- zip ------------------------------------------------------------ #
    step("Packing")
    if archive.exists():
        archive.unlink()
    count = _zip(stage, archive)
    info(f"{archive.name}  {count} files  {archive.stat().st_size / 1_048_576:.1f} MB")

    # Read the archive back rather than trusting the writer.
    with zipfile.ZipFile(archive) as bundle:
        broken = bundle.testzip()
        names = bundle.namelist()
    if broken:
        fail(f"the archive is corrupt at {broken}")
        return 1
    top = {name.split("/")[0] for name in names}
    if top != {stage.name}:
        fail(f"the archive does not extract to a single folder: {sorted(top)}")
        return 1
    info(f"archive verified: {len(names)} entries, all under {stage.name}/")

    print(f"\n   Released {APP_NAME} {version}")
    print(f"   folder   {stage}")
    print(f"   archive  {archive}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
